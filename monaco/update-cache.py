"""Generate a content-versioned, /monaco/-scoped offline service worker."""
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent
excluded = {'sw.js', 'update-cache.py', 'README.md'}
assets = sorted(p.relative_to(root).as_posix() for p in root.rglob('*')
                if p.is_file() and p.name not in excluded and not p.name.startswith('.'))
digest = hashlib.sha256()
for name in assets:
    digest.update(name.encode())
    digest.update((root / name).read_bytes())
version = digest.hexdigest()[:16]
template = r'''/* Generated by update-cache.py; only this guide's static assets are cached. */
'use strict';
const PREFIX = 'monaco-agent-fieldguide-';
const CACHE = PREFIX + '__VERSION__';
const BASE = new URL(self.registration.scope);
const ASSETS = __ASSETS__;
const URLS = ASSETS.map(path => new URL(path, BASE).href);
const ALLOWED = new Set(URLS);
const INDEX = new URL('index.html', BASE).href;
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(
    URLS.map(url => new Request(url, {cache: 'reload'}))
  )));
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== BASE.origin || !url.pathname.startsWith(BASE.pathname)) return;
  const navigation = request.mode === 'navigate' &&
    (url.pathname === BASE.pathname || url.pathname === new URL(INDEX).pathname);
  const key = navigation ? INDEX : url.origin + url.pathname;
  if (!navigation && !ALLOWED.has(key)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(key);
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok && response.type === 'basic') await cache.put(key, response.clone());
    return response;
  })());
});
self.addEventListener('message', event => {
  if (event.data?.type === 'ACTIVATE_UPDATE') {
    event.waitUntil(self.skipWaiting());
  }
  if (event.data?.type === 'CHECK_OFFLINE_COPY') {
    event.waitUntil((async () => {
      const cache = await caches.open(CACHE);
      let keys = new Set((await cache.keys()).map(request => request.url));
      const missing = URLS.filter(url => !keys.has(url));
      if (missing.length && event.data.repair === true) {
        try {
          await cache.addAll(missing.map(url => new Request(url, {cache: 'reload'})));
          keys = new Set((await cache.keys()).map(request => request.url));
        } catch { /* Report incomplete; keep the cached portion usable offline. */ }
      }
      event.source?.postMessage({type: 'OFFLINE_COPY_STATUS', complete: URLS.every(url => keys.has(url))});
    })());
  }
});
'''
(root / 'sw.js').write_text(template.replace('__VERSION__', version).replace('__ASSETS__', json.dumps(assets, indent=2)))
print(f'Prepared {len(assets)} offline assets; version {version}')
